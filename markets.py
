
class AdvancedMarkets:

    def __init__(
        self,
        home_team,
        away_team,
        home_lambda,
        away_lambda
    ):
        self.home_team = home_team
        self.away_team = away_team
        self.home_lambda = float(home_lambda)
        self.away_lambda = float(away_lambda)

    def get_advanced_predictions(self):

        total_goals = (
            self.home_lambda + self.away_lambda
        )

        if self.home_lambda > self.away_lambda:
            double_chance = "1X - Home or Draw"
        elif self.away_lambda > self.home_lambda:
            double_chance = "X2 - Away or Draw"
        else:
            double_chance = "Balanced - No clear side"

        if total_goals >= 3.0:
            goal_range = "3+ goals model estimate"
        elif total_goals >= 1.5:
            goal_range = "1-3 goals model estimate"
        else:
            goal_range = "0-2 goals model estimate"

        return {
            "Double Chance": double_chance,

            "HT/FT Prediction":
                "Requires first-half statistics",

            "Expected Total Goals":
                round(total_goals, 2),

            "Recommended Goal Range":
                goal_range,

            "Estimated Corners":
                "Requires corners statistics",

            "Booking Points / Cards":
                "Requires referee and team card statistics"
        }


if __name__ == "__main__":

    adv = AdvancedMarkets(
        "Simba SC",
        "Yanga SC",
        1.8,
        1.4
    )

    print(adv.get_advanced_predictions())
