
import math


class GunxMatchAnalyzer:

    def __init__(
        self,
        home_team,
        away_team,
        home_avg_goals,
        away_avg_goals
    ):
        self.home_team = home_team
        self.away_team = away_team
        self.home_lambda = float(home_avg_goals)
        self.away_lambda = float(away_avg_goals)

        if self.home_lambda < 0 or self.away_lambda < 0:
            raise ValueError("Expected goals cannot be negative")

        if not math.isfinite(self.home_lambda) or not math.isfinite(self.away_lambda):
            raise ValueError("Expected goals must be finite numbers")

    def calculate_poisson_probability(self, lmbda, goals):
        if lmbda == 0:
            return 1.0 if goals == 0 else 0.0

        return (
            math.exp(-lmbda)
            * (lmbda ** goals)
            / math.factorial(goals)
        )

    def analyze_match(self):

        home_win = 0.0
        draw = 0.0
        away_win = 0.0
        gg = 0.0
        over_35 = 0.0

        max_goals = 15

        for h in range(max_goals + 1):
            ph = self.calculate_poisson_probability(
                self.home_lambda, h
            )

            for a in range(max_goals + 1):
                pa = self.calculate_poisson_probability(
                    self.away_lambda, a
                )

                probability = ph * pa

                if h > a:
                    home_win += probability
                elif h == a:
                    draw += probability
                else:
                    away_win += probability

                if h > 0 and a > 0:
                    gg += probability

                if h + a >= 4:
                    over_35 += probability

        # Normalize probabilities
        total = home_win + draw + away_win

        if total <= 0:
            raise ValueError("Unable to calculate probabilities")

        home_win /= total
        draw /= total
        away_win /= total

        # GG / NG and Over / Under
        gg = min(max(gg, 0.0), 1.0)
        ng = 1.0 - gg

        over_35 = min(max(over_35, 0.0), 1.0)
        under_35 = 1.0 - over_35

        max_prob = max(home_win, draw, away_win)

        if max_prob >= 0.60:
            risk = "Lower Model Uncertainty"
        elif max_prob >= 0.45:
            risk = "Medium Model Uncertainty"
        else:
            risk = "High Model Uncertainty"

        results = {
            "Match": f"{self.home_team} vs {self.away_team}",

            "1X2 Probability": {
                f"{self.home_team} (1)": f"{home_win * 100:.2f}%",
                "Draw (X)": f"{draw * 100:.2f}%",
                f"{self.away_team} (2)": f"{away_win * 100:.2f}%"
            },

            "GG / NG": {
                "GG (Both Teams Score)": f"{gg * 100:.2f}%",
                "NG (BTTS No)": f"{ng * 100:.2f}%"
            },

            "Over / Under 3.5": {
                "Over 3.5": f"{over_35 * 100:.2f}%",
                "Under 3.5": f"{under_35 * 100:.2f}%"
            },

            "Risk Assessment": risk,

            "Model Expected Goals": {
                "Home": self.home_lambda,
                "Away": self.away_lambda,
                "Total": round(
                    self.home_lambda + self.away_lambda, 2
                )
            }
        }

        return results


if __name__ == "__main__":

    bot = GunxMatchAnalyzer(
        "Simba SC",
        "Yanga SC",
        1.8,
        1.4
    )

    print(bot.analyze_match())
