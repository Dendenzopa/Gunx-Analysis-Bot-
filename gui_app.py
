
from kivy.app import App
from kivy.metrics import dp
from kivy.uix.boxlayout import BoxLayout
from kivy.uix.gridlayout import GridLayout
from kivy.uix.label import Label
from kivy.uix.textinput import TextInput
from kivy.uix.button import Button
from kivy.uix.scrollview import ScrollView

from analyzer import GunxMatchAnalyzer
from markets import AdvancedMarkets


class GunxAnalysisApp(App):

    def build(self):
        self.title = "GUNX ANALYSIS BOT"

        root = BoxLayout(
            orientation="vertical",
            padding=dp(12),
            spacing=dp(10)
        )

        header = Label(
            text="[b]GUNX ANALYSIS BOT[/b]\nGLOBAL FOOTBALL ANALYSIS",
            markup=True,
            font_size="21sp",
            size_hint_y=None,
            height=dp(75)
        )
        root.add_widget(header)

        form = GridLayout(
            cols=2,
            spacing=dp(8),
            size_hint_y=None,
            row_default_height=dp(48),
            row_force_default=True
        )

        form.bind(
            minimum_height=form.setter("height")
        )

        self.home_entry = self.add_field(
            form, "Home Team", "Simba SC"
        )

        self.away_entry = self.add_field(
            form, "Away Team", "Yanga SC"
        )

        self.home_goals = self.add_field(
            form, "Home Avg Goals", "1.7"
        )

        self.away_goals = self.add_field(
            form, "Away Avg Goals", "1.5"
        )

        root.add_widget(form)

        analyze_button = Button(
            text="CHAMBUA MECHI",
            size_hint_y=None,
            height=dp(52),
            background_normal="",
            background_color=(0.05, 0.48, 0.20, 1),
            bold=True
        )

        analyze_button.bind(
            on_press=self.analyze_match
        )

        root.add_widget(analyze_button)

        scroll = ScrollView(
            size_hint=(1, 1)
        )

        self.output = Label(
            text="Ingiza taarifa za mechi kisha bonyeza CHAMBUA MECHI.",
            font_size="14sp",
            halign="left",
            valign="top",
            size_hint_y=None,
            padding=(dp(8), dp(8))
        )

        self.output.bind(
            width=lambda instance, width:
            setattr(instance, "text_size", (width, None))
        )

        self.output.bind(
            texture_size=lambda instance, size:
            setattr(instance, "height", size[1] + dp(20))
        )

        scroll.add_widget(self.output)
        root.add_widget(scroll)

        return root

    def add_field(self, layout, label_text, default_value):

        label = Label(
            text=label_text,
            font_size="13sp"
        )

        field = TextInput(
            text=default_value,
            multiline=False,
            size_hint_y=None,
            height=dp(45),
            font_size="15sp"
        )

        layout.add_widget(label)
        layout.add_widget(field)

        return field

    def analyze_match(self, instance):

        home = self.home_entry.text.strip()
        away = self.away_entry.text.strip()

        if not home or not away:
            self.output.text = "KOSA: Tafadhali jaza majina ya timu."
            return

        try:
            h_goals = float(self.home_goals.text)
            a_goals = float(self.away_goals.text)

            if h_goals < 0 or a_goals < 0:
                raise ValueError

            bot = GunxMatchAnalyzer(
                home,
                away,
                h_goals,
                a_goals
            )

            analysis = bot.analyze_match()

            advanced_bot = AdvancedMarkets(
                home,
                away,
                h_goals,
                a_goals
            )

            advanced = advanced_bot.get_advanced_predictions()

            result = []

            result.append("GUNX MATCH ANALYSIS")
            result.append("=" * 30)
            result.append(analysis["Match"])
            result.append("")
            result.append("1X2 PROBABILITY")

            for market, value in analysis["1X2 Probability"].items():
                result.append(f"{market}: {value}")

            result.append("")
            result.append("GOALS MARKETS")

            for market, value in analysis["GG / NG"].items():
                result.append(f"{market}: {value}")

            for market, value in analysis["Over / Under 3.5"].items():
                result.append(f"{market}: {value}")

            result.append("")
            result.append("ADVANCED MARKETS")
            result.append(
                f"Double Chance: {advanced['Double Chance']}"
            )
            result.append(
                f"HT/FT: {advanced['HT/FT Prediction']}"
            )
            result.append(
                f"Goal Range: {advanced['Recommended Goal Range']}"
            )
            result.append(
                f"Expected Goals: {advanced['Expected Total Goals']}"
            )
            result.append(
                f"Corners: {advanced['Estimated Corners']}"
            )
            result.append(
                f"Cards: {advanced['Booking Points / Cards']}"
            )

            result.append("")
            result.append(
                f"Model Assessment: {analysis['Risk Assessment']}"
            )

            result.append("")
            result.append(
                "NOTE: Haya ni makadirio ya modeli, si uhakika wa matokeo."
            )

            self.output.text = "\n".join(result)

        except ValueError:
            self.output.text = (
                "KOSA: Weka wastani wa magoli kama namba sahihi "
                "zisizo chini ya sifuri."
            )

        except Exception as error:
            self.output.text = (
                f"Hitilafu ya uchambuzi: {error}"
            )


if __name__ == "__main__":
    GunxAnalysisApp().run()
